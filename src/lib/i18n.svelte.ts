class I18nManager {
  locale = $state<Locale>(I18nManager.initialLocale());

  private static initialLocale(): Locale {
    const stored = storageGet('klipper_lang');
    return stored && stored in dictionaries ? (stored as Locale) : 'en';
  }

  t(key: string, params: Record<string, string | number> = {}): string {
    const dict = dictionaries[this.locale] || dictionaries.en;
    let text = dict[key] || dictionaries.en[key] || key;

    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return text;
  }

  setLocale(lang: Locale) {
    this.locale = lang;
    storageSet('klipper_lang', lang);
  }
}

export const i18n = new I18nManager();
