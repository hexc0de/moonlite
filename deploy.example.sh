#!/usr/bin/env bash
# Build Moonlite and deploy it to a Klipper host as a separate nginx site.
#
# Template: copy it to deploy.sh (gitignored) and put your printer's defaults there:
#   cp deploy.example.sh deploy.sh
#
# Usage: ./deploy.sh <printer-host>
# Overridable via environment: PRINTER_HOST, PRINTER_USER, REMOTE_DIR, NGINX_PORT,
# MOONRAKER_UPSTREAM, WEBCAM_UPSTREAM.
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
cd "$DIR"

PRINTER_HOST="${1:-${PRINTER_HOST:-}}"
PRINTER_USER="${PRINTER_USER:-pi}"

if [[ -z "${PRINTER_HOST}" ]]; then
  echo "Usage: $0 <printer-host>   (or set PRINTER_HOST)" >&2
  exit 1
fi
REMOTE_DIR="${REMOTE_DIR:-/home/${PRINTER_USER}/moonlite}"
NGINX_PORT="${NGINX_PORT:-81}"
# Proxied directly, so the site does not depend on Mainsail's nginx upstream definitions.
MOONRAKER_UPSTREAM="${MOONRAKER_UPSTREAM:-127.0.0.1:7125}"
WEBCAM_UPSTREAM="${WEBCAM_UPSTREAM:-127.0.0.1:8080}"

TARGET="${PRINTER_USER}@${PRINTER_HOST}"
NGINX_TEMPLATE="${DIR}/nginx/moonlite.conf"

# Escape a value for use in a sed replacement with '|' as the delimiter.
sed_escape() { printf '%s' "$1" | sed -e 's/[\\|&]/\\&/g'; }

# Fill the {{...}} placeholders of the nginx site template.
render_nginx_config() {
  echo "# Generated by Moonlite deploy.sh from nginx/moonlite.conf; changes will be overwritten."
  echo
  sed -e "s|{{NGINX_PORT}}|$(sed_escape "${NGINX_PORT}")|g" \
      -e "s|{{ROOT_DIR}}|$(sed_escape "${REMOTE_DIR}")|g" \
      -e "s|{{MOONRAKER_UPSTREAM}}|$(sed_escape "${MOONRAKER_UPSTREAM}")|g" \
      -e "s|{{WEBCAM_UPSTREAM}}|$(sed_escape "${WEBCAM_UPSTREAM}")|g" \
      "${NGINX_TEMPLATE}"
}

# Render before anything touches the printer, so a broken template fails early.
NGINX_CONF="$(render_nginx_config)"
if grep -q '{{[A-Z_]*}}' <<<"${NGINX_CONF}"; then
  echo "Unfilled placeholders in ${NGINX_TEMPLATE}:" >&2
  grep -o '{{[A-Z_]*}}' <<<"${NGINX_CONF}" | sort -u >&2
  exit 1
fi

echo "=== 1. Building Moonlite production bundle ==="
npm run build

echo "=== 2. Creating ${REMOTE_DIR} on ${PRINTER_HOST} ==="
ssh "${TARGET}" "mkdir -p '${REMOTE_DIR}'"

echo "=== 3. Uploading dist files ==="
rsync -avz --delete dist/ "${TARGET}:${REMOTE_DIR}/"

echo "=== 4. Setting up nginx site on port ${NGINX_PORT} ==="
printf '%s\n' "${NGINX_CONF}" | ssh "${TARGET}" "sudo tee /etc/nginx/sites-available/moonlite > /dev/null"

echo "=== 5. Enabling nginx site and reloading ==="
ssh "${TARGET}" "sudo ln -sf /etc/nginx/sites-available/moonlite /etc/nginx/sites-enabled/moonlite && sudo nginx -t && sudo systemctl reload nginx"

echo ""
echo "=========================================================="
echo "  Moonlite deployed to ${PRINTER_HOST}"
echo "  URL: http://${PRINTER_HOST}:${NGINX_PORT}/"
if [[ "${NGINX_PORT}" != "80" ]]; then
  echo "  Existing UI on port 80 (Mainsail/Fluidd) is untouched."
fi
echo "=========================================================="
